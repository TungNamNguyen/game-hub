export function t(key, vars = {}) {
  const table = DICTS[currentLang] || DICTS.vi;
  let tpl = table[key];
  if (tpl === undefined) tpl = DICTS.vi[key];
  if (tpl === undefined) return key;
  if (!vars || typeof tpl !== 'string') return tpl;
  return tpl.replace(/\{([a-zA-Z0-9_]+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

