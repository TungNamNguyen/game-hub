/* Quản lý đa ngôn ngữ (Tiếng Việt / English) cho toàn bộ Game Hub.
 *
 * Lưu lựa chọn ở localStorage['hub.lang'] (mặc định 'vi'), cập nhật <html lang>
 * ngay khi import và thông báo qua onLangChange() để giao diện vẽ lại tức thì
 * mà không làm ngắt kết nối WebSocket.
 */

const LANG_KEY = 'hub.lang';
const SUPPORTED = new Set(['vi', 'en']);
const listeners = new Set();

function readInitialLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (SUPPORTED.has(saved)) return saved;
  } catch { /* môi trường test hoặc private mode */ }
  return 'vi';
}

let currentLang = readInitialLang();

function syncDocLang(lang) {
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
  }
}
syncDocLang(currentLang);

export function getLang() {
  return currentLang;
}

export function locale() {
  return currentLang === 'en' ? 'en-US' : 'vi-VN';
}

export function setLang(lang, { notify = true } = {}) {
  const next = SUPPORTED.has(lang) ? lang : 'vi';
  const changed = next !== currentLang;
  currentLang = next;
  try { localStorage.setItem(LANG_KEY, next); } catch { /* bỏ qua */ }
  syncDocLang(next);
  if (changed && notify) {
    for (const fn of [...listeners]) {
      try { fn(next); } catch (err) { console.error('i18n listener error', err); }
    }
  }
  return next;
}

export function toggleLang() {
  return setLang(currentLang === 'vi' ? 'en' : 'vi');
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

